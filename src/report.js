/** Markdown report export. */
const { countBySeverity } = require('./rules');
const { grade } = require('./render');

const EMOJI = { critical: '🔴', warning: '🟡', suggestion: '🔵' };

function toMarkdown(result, { date = new Date() } = {}) {
    const counts = countBySeverity(result.issues);
    const mode = result.mode === 'ai' ? `AI · ${result.provider}` : 'Offline';
    const lines = [
        '# 🔍 CodeLens Review',
        '',
        `> Generated by [Prism CodeLens](https://github.com/krishyaa06/prism-codelens) on ${date.toISOString().slice(0, 10)}`,
        '',
        '| Score | Grade | Mode | Files | 🔴 Critical | 🟡 Warnings | 🔵 Suggestions |',
        '|:-----:|:-----:|:----:|:-----:|:----:|:----:|:----:|',
        `| **${result.score}/100** | **${grade(result.score)}** | ${mode} | ${result.files.length} `
            + `| ${counts.critical} | ${counts.warning} | ${counts.suggestion} |`,
        '',
        '## Summary',
        '',
        result.summary || '_No summary._',
        ''
    ];
    if (result.highlights?.length) {
        lines.push('## ✅ What looks good', '', ...result.highlights.map(h => `- ${h}`), '');
    }
    lines.push('## Issues', '');
    if (!result.issues.length) lines.push('No issues found. ✨', '');
    for (const sev of ['critical', 'warning', 'suggestion']) {
        const list = result.issues.filter(i => i.severity === sev);
        if (!list.length) continue;
        lines.push(`### ${EMOJI[sev]} ${sev[0].toUpperCase() + sev.slice(1)} (${list.length})`, '');
        for (const i of list) {
            lines.push(`#### ${i.title}`, '', `\`${i.file}${i.line ? ':' + i.line : ''}\` · ${i.category}`, '');
            if (i.snippet) lines.push('```', i.snippet, '```', '');
            if (i.detail) lines.push(i.detail, '');
            if (i.fix) lines.push(`**Fix:** ${i.fix}`, '');
        }
    }
    return lines.join('\n');
}

module.exports = { toMarkdown };
